USE revguard_db;

-- =========================================================================
-- 1. RFM (Recency, Frequency, Monetary) Segmentation View
-- =========================================================================
CREATE OR REPLACE VIEW vw_customer_rfm AS
SELECT 
    c.customer_id,
    c.subscription_tier,
    c.acquisition_channel,
    c.is_churned,
    -- Recency: Days since the customer's last successful transaction relative to max date in data
    DATEDIFF('2025-10-01', MAX(t.transaction_date)) AS recency_days,
    -- Frequency: Total successful transactions count
    COUNT(t.transaction_id) AS frequency_count,
    -- Monetary: Total revenue generated by the customer
    SUM(t.amount) AS monetary_total
FROM dim_customers c
JOIN fact_transactions t ON c.customer_id = t.customer_id
WHERE t.payment_status = 'Success'
GROUP BY c.customer_id, c.subscription_tier, c.acquisition_channel, c.is_churned;


-- =========================================================================
-- 2. Customer Value & Support Friction View
-- =========================================================================
CREATE OR REPLACE VIEW vw_customer_value_friction AS
SELECT 
    c.customer_id,
    c.subscription_tier,
    c.is_churned,
    COALESCE(SUM(t.amount), 0) AS total_spend,
    COUNT(DISTINCT t.transaction_id) AS total_invoices,
    COALESCE(u.avg_logins, 0) AS avg_monthly_logins,
    COALESCE(s.total_tickets, 0) AS total_support_tickets,
    COALESCE(s.avg_resolution_time, 0) AS avg_resolution_time_hours
FROM dim_customers c
LEFT JOIN fact_transactions t ON c.customer_id = t.customer_id AND t.payment_status = 'Success'
LEFT JOIN (
    customer_id, 
    AVG(login_count) AS avg_logins 
    FROM fact_usage_monthly 
    GROUP BY customer_id
) u ON c.customer_id = u.customer_id
LEFT JOIN (
    SELECT 
        customer_id, 
        COUNT(ticket_id) AS total_tickets,
        AVG(resolution_time_hours) AS avg_resolution_time
    FROM fact_support_tickets
    GROUP BY customer_id
) s ON c.customer_id = s.customer_id
GROUP BY c.customer_id, c.subscription_tier, c.is_churned, u.avg_logins, s.total_tickets, s.avg_resolution_time;


-- =========================================================================
-- 3. Monthly Cohort Revenue Retention View
-- =========================================================================
CREATE OR REPLACE VIEW vw_cohort_monthly_revenue AS
SELECT 
    DATE_FORMAT(c.signup_date, '%Y-%m-01') AS cohort_month,
    DATE_FORMAT(t.transaction_date, '%Y-%m-01') AS transaction_month,
    COUNT(DISTINCT c.customer_id) AS active_customers,
    SUM(t.amount) AS monthly_revenue
FROM dim_customers c
JOIN fact_transactions t ON c.customer_id = t.customer_id
WHERE t.payment_status = 'Success'
GROUP BY cohort_month, transaction_month;